/**
 * AI Code Reviewer - GitHub API Integration
 * Handles fetching PR details/diff, comparing re-reviews, and publishing structured reviews.
 */

export class GitHubClient {
  constructor({ token, owner, repo, apiUrl = 'https://api.github.com' }) {
    if (!token) {
      throw new Error('GitHubClient requires an authenticated token');
    }
    this.token = token;
    this.owner = owner;
    this.repo = repo;
    this.apiUrl = apiUrl.replace(/\/$/, '');
  }

  async request(endpoint, options = {}) {
    const url = `${this.apiUrl}/repos/${this.owner}/${this.repo}${endpoint}`;
    const headers = {
      Authorization: `token ${this.token}`,
      Accept: 'application/vnd.github.v3+json',
      'User-Agent': 'Independent-AI-Code-Reviewer',
      ...options.headers
    };

    const res = await fetch(url, { ...options, headers });
    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`GitHub API error ${res.status} on ${endpoint}: ${errText}`);
    }
    return res;
  }

  async getPullRequest(prNumber) {
    const res = await this.request(`/pulls/${prNumber}`);
    return await res.json();
  }

  async getPullRequestDiff(prNumber) {
    const res = await this.request(`/pulls/${prNumber}`, {
      headers: { Accept: 'application/vnd.github.v3.diff' }
    });
    return await res.text();
  }

  async getPreviousReviews(prNumber) {
    const res = await this.request(`/pulls/${prNumber}/reviews`);
    return await res.json();
  }

  /**
   * Extracts previously reported findings from the latest review body payload.
   */
  extractPreviousFindings(previousReviews) {
    if (!Array.isArray(previousReviews) || previousReviews.length === 0) {
      return null;
    }

    // Iterate backwards to find the latest review generated by AI Reviewer
    for (let i = previousReviews.length - 1; i >= 0; i--) {
      const review = previousReviews[i];
      if (!review.body) continue;

      const match = review.body.match(/<!-- AI_REVIEW_PAYLOAD:\s*([\s\S]*?)\s*-->/);
      if (match && match[1]) {
        try {
          const payload = JSON.parse(match[1]);
          return {
            commitSha: payload.commitSha || review.commit_id,
            findings: Array.isArray(payload.findings) ? payload.findings : []
          };
        } catch (_) {
          // Ignore malformed payload and continue backwards
        }
      }
    }
    return null;
  }

  /**
   * Compares current findings with previous findings (Phase 7 Re-review).
   */
  compareFindings(previousFindings, currentFindings) {
    if (!previousFindings) {
      return {
        hasPreviousReview: false,
        resolved: [],
        unresolved: [],
        newFindings: currentFindings
      };
    }

    const currentKeys = new Set(
      currentFindings.map((f) => `${f.file}:${f.title}`.toLowerCase())
    );
    const previousKeys = new Set(
      previousFindings.map((f) => `${f.file}:${f.title}`.toLowerCase())
    );

    const resolved = previousFindings.filter(
      (pf) => !currentKeys.has(`${pf.file}:${pf.title}`.toLowerCase())
    );

    const unresolved = currentFindings.filter(
      (cf) => previousKeys.has(`${cf.file}:${cf.title}`.toLowerCase())
    );

    const newFindings = currentFindings.filter(
      (cf) => !previousKeys.has(`${cf.file}:${cf.title}`.toLowerCase())
    );

    return {
      hasPreviousReview: true,
      previousCount: previousFindings.length,
      resolved,
      unresolved,
      newFindings
    };
  }

  /**
   * Publishes the structured AI review on the PR with commit SHA binding and re-review tracking.
   */
  async publishReview({ prNumber, commitSha, reviewData, testReport = null }) {
    const { assessment, summary, findings, architecturalObservations } = reviewData;

    // Fetch previous reviews to calculate resolved/unresolved issues
    let comparison = { hasPreviousReview: false, resolved: [], unresolved: [], newFindings: findings };
    try {
      const previousReviews = await this.getPreviousReviews(prNumber);
      const previousData = this.extractPreviousFindings(previousReviews);
      if (previousData) {
        comparison = this.compareFindings(previousData.findings, findings);
      }
    } catch (err) {
      console.warn(`[AI Reviewer] Could not retrieve previous reviews for comparison: ${err.message}`);
    }

    // Map assessment to GitHub review event
    let event = 'COMMENT';
    if (assessment === 'APPROVED') {
      event = 'APPROVE';
    } else if (assessment === 'CHANGES_REQUESTED') {
      event = 'REQUEST_CHANGES';
    }

    const markdownBody = this.buildReviewMarkdown({
      commitSha,
      assessment,
      summary,
      findings,
      architecturalObservations,
      testReport,
      comparison
    });

    const inlineComments = findings
      .filter((f) => f.file && f.line)
      .map((f) => ({
        path: f.file,
        line: f.line,
        body: `**[${f.severity}] ${f.title}**\n\n${f.explanation}\n\n*תרחיש השפעה:* ${f.impactScenario}\n\n*תיקון מומלץ:* ${f.remediation}`
      }));

    try {
      const payload = {
        commit_id: commitSha,
        body: markdownBody,
        event,
        comments: inlineComments
      };

      const res = await this.request(`/pulls/${prNumber}/reviews`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
      return await res.json();
    } catch (inlineErr) {
      console.warn(`[AI Reviewer] Inline comments could not be anchored (${inlineErr.message}). Falling back to main review body.`);

      const fallbackBody = `${markdownBody}\n\n### פירוט ממצאים\n\n` +
        findings.map((f) => `#### [${f.severity}] ${f.title}\n- **קובץ**: \`${f.file}\` (שורה ${f.line})\n- **הסבר**: ${f.explanation}\n- **תרחיש השפעה**: ${f.impactScenario}\n- **תיקון מוצע**: ${f.remediation}`).join('\n\n');

      const fallbackPayload = {
        commit_id: commitSha,
        body: fallbackBody,
        event
      };

      const res = await this.request(`/pulls/${prNumber}/reviews`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(fallbackPayload)
      });
      return await res.json();
    }
  }

  buildReviewMarkdown({ commitSha, assessment, summary, findings, architecturalObservations, testReport, comparison }) {
    const timestamp = new Date().toISOString();
    const severityCounts = {
      CRITICAL: findings.filter((f) => f.severity === 'CRITICAL').length,
      HIGH: findings.filter((f) => f.severity === 'HIGH').length,
      MEDIUM: findings.filter((f) => f.severity === 'MEDIUM').length,
      LOW: findings.filter((f) => f.severity === 'LOW').length,
      INFO: findings.filter((f) => f.severity === 'INFO').length
    };

    const statusBadge = {
      APPROVED: '✅ אושר ללא חסימות',
      CHANGES_REQUESTED: '❌ נדרשים שינויים מהותיים',
      REVIEW_WITH_WARNINGS: '⚠️ ביקורת עם אזהרות',
      REVIEW_PASSED_WITH_NOTES: 'ℹ️ ביקורת עברה עם הערות'
    }[assessment] || assessment;

    let testStatus = 'לא הופעלו בדיקות';
    if (testReport && testReport.executed) {
      testStatus = testReport.success
        ? `✅ ${testReport.passedCount} בדיקות עברו בהצלחה (${testReport.durationMs}ms)`
        : `❌ נכשלו בדיקות (${testReport.failedCount} כשלים)`;
    }

    let reReviewSection = '';
    if (comparison && comparison.hasPreviousReview) {
      const resolvedList = comparison.resolved.length > 0
        ? comparison.resolved.map((r) => `- ✅ **[${r.severity}] ${r.title}** (\`${r.file}\`)`).join('\n')
        : '- לא תועדו ממצאים שנפתרו בדחיפה זו.';

      const unresolvedList = comparison.unresolved.length > 0
        ? comparison.unresolved.map((u) => `- ⚠️ **[${u.severity}] ${u.title}** (\`${u.file}\`)`).join('\n')
        : '- אין ממצאים פתוחים מהגרסה הקודמת.';

      const newList = comparison.newFindings.length > 0
        ? comparison.newFindings.map((n) => `- 🆕 **[${n.severity}] ${n.title}** (\`${n.file}\`)`).join('\n')
        : '- לא התגלו פגמים חדשים בדחיפה זו.';

      reReviewSection = `
### מעקב שינויים והשוואה לביקורת קודמת
- **ממצאים שתוקנו ונפתרו**: ${comparison.resolved.length}
- **ממצאים שנותרו פתוחים**: ${comparison.unresolved.length}
- **ממצאים חדשים שהתגלו**: ${comparison.newFindings.length}

<details>
<summary>פירוט מעקב שינויים</summary>

#### ממצאים שנפתרו
${resolvedList}

#### ממצאים שנותרו פתוחים
${unresolvedList}

#### ממצאים חדשים
${newList}

</details>
`;
    }

    // Prepare embedded payload for subsequent re-reviews
    const embeddedPayload = JSON.stringify({
      commitSha,
      findings: findings.map((f) => ({
        severity: f.severity,
        title: f.title,
        file: f.file,
        line: f.line
      }))
    });

    return `## ביקורת קוד עצמאית

- **מזהה התחייבות**: \`${commitSha.slice(0, 8)}\`
- **מועד ביקורת**: \`${timestamp}\`
- **הערכה כוללת**: **${statusBadge}**
- **סטטוס בדיקות אוטומטיות**: ${testStatus}

### סיכום ממצאים לפי חומרה
- **קריטי**: ${severityCounts.CRITICAL}
- **גבוה**: ${severityCounts.HIGH}
- **בינוני**: ${severityCounts.MEDIUM}
- **נמוך**: ${severityCounts.LOW}
- **מידע**: ${severityCounts.INFO}
${reReviewSection}
---

### הערכת הבודק
${summary}

${
  architecturalObservations && architecturalObservations.length > 0
    ? `### תצפיות ארכיטקטוניות\n${architecturalObservations.map((obs) => `- ${obs}`).join('\n')}`
    : ''
}

> [!NOTE]
> ביקורת זו הופקה באופן עצמאי ומבודד לחלוטין ללא שיתוף היסטוריית השיחה של הסוכן המפתח. אישור המיזוג הסופי נותר באחריות המפתח האנושי בלבד.

<!-- AI_REVIEW_PAYLOAD: ${embeddedPayload} -->`;
  }
}
